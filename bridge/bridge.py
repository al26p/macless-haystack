#!/usr/bin/env python3
"""Bridge Apple FindMy (macless-haystack) reports into a Traccar server.

Every run it:

  1. reads a map of ``{traccar-device-name: privateKey}`` (the private keys
     generated by macless-haystack's ``generate_keys.py``). A device may also
     list rotating keys as ``{name: [privateKey, *additionalKeys]}``,
  2. derives the Apple ``id`` (hashed advertisement key) for each key,
  3. asks the macless-haystack endpoint for the last ``QUERY_DAYS`` of reports,
  4. decrypts each report locally,
  5. drops reports already seen in a previous run (state file), and
  6. replays the remaining positions, oldest first, into Traccar's OsmAnd
     protocol endpoint at their original fix time.

Traccar accepts historical timestamps on the OsmAnd endpoint, so this backfills
the last N days of Apple FindMy locations into Traccar's trip/history pipeline.
"""

import base64
import hashlib
import json
import logging
import os
import sys
from collections import Counter
from datetime import datetime, timezone

import requests
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

LOGGER = logging.getLogger("macless-bridge")

APPLE_EPOCH_OFFSET = 978307200  # seconds between 1970-01-01 and 2001-01-01
CURVE = ec.SECP224R1()


def env(name, default=None):
    value = os.environ.get(name)
    return value if value not in (None, "") else default


def env_bool(name, default):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in ("1", "true", "yes", "on")


# ---------------------------------------------------------------------------
# Key handling
# ---------------------------------------------------------------------------

def derive_apple_id(private_key_b64):
    """Return the Apple search id (base64 sha256 of the adv public key x)."""
    key_bytes = base64.b64decode(private_key_b64)
    private_key = ec.derive_private_key(
        int.from_bytes(key_bytes, "big"), CURVE)
    adv_x = private_key.public_key().public_numbers().x
    adv_bytes = adv_x.to_bytes(28, "big")
    return base64.b64encode(hashlib.sha256(adv_bytes).digest()).decode("ascii")


def parse_device(value, source):
    """Normalize one device entry to a list of private keys.

    Accepts either a bare private key string (the original flat format) or a
    list whose first entry is the leading key and the rest are the additional
    rotating keys advertised by the tag.
    """
    if isinstance(value, str):
        if not value:
            raise ValueError(f"{source}: private key is empty")
        return [value]
    if isinstance(value, list):
        if not value or not all(
                isinstance(key, str) and key for key in value):
            raise ValueError(
                f"{source}: device must be a non-empty list of private keys")
        return list(value)
    raise ValueError(
        f"{source}: device must be a private key string or a list of keys")


def parse_devices(data, source):
    """Normalize parsed JSON to {name: [privateKey, ...]}.

    The format is a flat object keyed by Traccar device name. Each value is
    either a private key string or a list of private keys (leading key first,
    followed by the additional rotating keys).
    """
    if not isinstance(data, dict):
        raise ValueError(f"{source} must contain a JSON object")
    return {str(name): parse_device(value, f"{source}: {name}")
            for name, value in data.items()}


def load_devices():
    """Load {name: [privateKey, ...]} from a JSON file or a directory of files."""
    devices_file = env("DEVICES_FILE")
    if devices_file and os.path.isfile(devices_file):
        with open(devices_file, encoding="utf-8") as handle:
            data = json.load(handle)
        return parse_devices(data, devices_file)

    devices_dir = env("DEVICES_DIR")
    if devices_dir and os.path.isdir(devices_dir):
        devices = {}
        for entry in sorted(os.listdir(devices_dir)):
            path = os.path.join(devices_dir, entry)
            if os.path.isfile(path):
                with open(path, encoding="utf-8") as handle:
                    devices[entry] = [handle.read().strip()]
        return devices

    raise RuntimeError(
        "no device keys found: set DEVICES_FILE to a JSON map or DEVICES_DIR")


# ---------------------------------------------------------------------------
# Decryption (OpenHaystack / Apple FindMy report format)
# ---------------------------------------------------------------------------

def decrypt_report(private_key, payload_b64):
    """Decrypt one report payload -> dict with position fields."""
    payload = base64.b64decode(payload_b64)
    if len(payload) > 88:
        payload = payload[:4] + payload[5:]

    timestamp = int.from_bytes(payload[0:4], "big", signed=True) + APPLE_EPOCH_OFFSET
    confidence = payload[4]
    ephemeral_key_bytes = payload[5:62]
    encrypted = payload[62:]

    ephemeral_key = ec.EllipticCurvePublicKey.from_encoded_point(
        CURVE, ephemeral_key_bytes)
    shared = private_key.exchange(ec.ECDH(), ephemeral_key)
    symmetric = hashlib.sha256(
        shared + b"\x00\x00\x00\x01" + ephemeral_key_bytes).digest()

    plaintext = AESGCM(symmetric[:16]).decrypt(symmetric[16:], encrypted, None)

    latitude = int.from_bytes(plaintext[0:4], "big", signed=True) / 1e7
    longitude = int.from_bytes(plaintext[4:8], "big", signed=True) / 1e7
    accuracy = plaintext[8]
    status = plaintext[9]

    return {
        "timestamp": timestamp,
        "latitude": latitude,
        "longitude": longitude,
        "accuracy": accuracy,
        "confidence": confidence,
        "status": status,
        "battery": battery_from_status(status),
    }


def battery_from_status(status):
    """Map the status byte to a battery label (macless / pix firmwares)."""
    if (status & 0o0100000) == 0 and status == 0:
        return None
    return {0: "ok", 1: "medium", 2: "low", 3: "critical"}.get(status >> 6)


BATTERY_LEVEL = {"ok": 100, "medium": 60, "low": 30, "critical": 5}


# ---------------------------------------------------------------------------
# State (dedup across the overlapping 24h windows)
# ---------------------------------------------------------------------------

def load_state(path, now, max_age):
    try:
        with open(path, encoding="utf-8") as handle:
            state = json.load(handle)
        seen = state.get("seen", {})
    except (OSError, ValueError):
        seen = {}
    pruned = {k: v for k, v in seen.items() if now - v <= max_age}
    return pruned


def save_state(path, seen):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump({"version": 1, "seen": seen}, handle)
    os.replace(tmp, path)


# ---------------------------------------------------------------------------
# macless-haystack endpoint
# ---------------------------------------------------------------------------

def fetch_reports(session, endpoint_url, apple_ids, days, timeout, per_device):
    """Ask the endpoint for reports.

    By default each id is queried on its own (one ``/find`` request per key,
    matching the macless frontend). A tag that rotates through many keys will
    issue one request per key this way; set ``MH_PER_DEVICE=false`` to batch
    ids into ``MH_MAX_IDS``-sized requests (raise ``MH_MAX_IDS`` above the total
    key count to send everything in a single request).
    """
    if per_device:
        batches = [[apple_id] for apple_id in apple_ids]
    else:
        chunk_size = int(env("MH_MAX_IDS", "100"))
        batches = [apple_ids[start:start + chunk_size]
                   for start in range(0, len(apple_ids), chunk_size)]

    results = []
    for batch in batches:
        response = session.post(
            endpoint_url, json={"ids": batch, "days": days}, timeout=timeout)
        if response.status_code == 503:
            raise ReloginRequired(response.text)
        response.raise_for_status()
        results.extend(response.json().get("results", []))
    return results


class ReloginRequired(Exception):
    pass


# ---------------------------------------------------------------------------
# Traccar (OsmAnd protocol)
# ---------------------------------------------------------------------------

def build_params(name, position):
    """Build the OsmAnd query for one position.

    The report timestamp is sent in milliseconds and is never replaced by the
    current time, so Traccar stores the position at its original fix time.
    """
    params = {
        "id": name,
        "timestamp": position["timestamp"] * 1000,
        "lat": f"{position['latitude']:.7f}",
        "lon": f"{position['longitude']:.7f}",
        "conf": position["confidence"],
        "status": position["status"],
        "accuracy": position["accuracy"],
    }
    level = BATTERY_LEVEL.get(position["battery"])
    if level is not None:
        params["batt"] = level
    return params


def post_position(session, traccar_url, name, position, timeout):
    response = session.get(
        traccar_url, params=build_params(name, position), timeout=timeout)
    response.raise_for_status()
    return response

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def run():
    endpoint_url = env("MH_ENDPOINT_URL", "http://macless-haystack:6176/find")
    traccar_url = env("TRACCAR_URL", "http://traccar:5055")
    state_path = env("STATE_FILE", "/state/seen.json")
    days = float(env("QUERY_DAYS", "1"))
    timeout = float(env("HTTP_TIMEOUT", "60"))
    verify_tls = env_bool("MH_VERIFY_TLS", True)
    dry_run = env_bool("DRY_RUN", False)

    auth = None
    if env("MH_ENDPOINT_USER"):
        auth = (env("MH_ENDPOINT_USER"), env("MH_ENDPOINT_PASS", ""))

    devices = load_devices()
    if not devices:
        LOGGER.error("no devices configured, nothing to do")
        return 1

    by_id = {}
    for name, private_keys in devices.items():
        for private_key_b64 in private_keys:
            private_key = ec.derive_private_key(
                int.from_bytes(base64.b64decode(private_key_b64), "big"), CURVE)
            by_id[derive_apple_id(private_key_b64)] = (name, private_key)

    per_device = env_bool("MH_PER_DEVICE", True)
    LOGGER.info("Querying %s for %d key(s) across %d device(s), last %s day(s), %s",
                endpoint_url, len(by_id), len(devices), days,
                "one request per key" if per_device else "batched")

    now = int(datetime.now(timezone.utc).timestamp())
    seen = load_state(state_path, now, max_age=int(env("STATE_MAX_AGE", "172800")))

    session = requests.Session()
    session.auth = auth
    session.verify = verify_tls

    try:
        reports = fetch_reports(
            session, endpoint_url, list(by_id), days, timeout, per_device)
    except ReloginRequired as error:
        LOGGER.error("macless-haystack needs a new Apple login (%s): "
                     "POST /login then /2fa", error)
        return 0
    except requests.RequestException as error:
        LOGGER.error("fetching reports failed: %s", error)
        return 1

    LOGGER.info("Received %d raw report(s)", len(reports))

    positions = []
    for report in reports:
        entry = by_id.get(report.get("id"))
        if entry is None:
            LOGGER.warning("report for unknown id %s, skipping", report.get("id"))
            continue
        name, private_key = entry
        try:
            decoded = decrypt_report(private_key, report["payload"])
        except Exception as error:  # noqa: BLE001 - single bad report must not abort
            LOGGER.warning("could not decrypt report for %s: %s", name, error)
            continue
        decoded["name"] = name
        decoded["state_key"] = hashlib.sha256(
            report["payload"].encode("ascii")).hexdigest()
        positions.append(decoded)

    counts = Counter(position["name"] for position in positions)
    for device_name in devices:
        LOGGER.info("  %s: %d report(s)", device_name, counts.get(device_name, 0))

    positions.sort(key=lambda item: item["timestamp"])

    posted = 0
    for position in positions:
        if position["state_key"] in seen:
            continue
        if dry_run:
            LOGGER.info("[dry-run] %s @ %s (%.5f, %.5f) conf=%s status=%s batt=%s",
                        position["name"], position["timestamp"],
                        position["latitude"], position["longitude"],
                        position["confidence"], position["status"],
                        position["battery"])
            continue
        try:
            post_position(session, traccar_url, position["name"], position, timeout)
        except requests.RequestException as error:
            LOGGER.error("posting %s @ %s failed: %s",
                         position["name"], position["timestamp"], error)
            continue
        seen[position["state_key"]] = position["timestamp"]
        posted += 1
        LOGGER.debug("posted %s @ %s (%.5f, %.5f)",
                     position["name"], position["timestamp"],
                     position["latitude"], position["longitude"])

    if dry_run:
        LOGGER.info("Dry run: %d new position(s) would be posted", len(positions))
        return 0

    save_state(state_path, seen)
    LOGGER.info("Posted %d new position(s), %d already seen",
                posted, len(positions) - posted)
    return 0


def main():
    logging.basicConfig(
        level=env("LOG_LEVEL", "INFO").upper(),
        format="%(asctime)s %(levelname)s %(message)s")
    try:
        sys.exit(run())
    except Exception as error:  # noqa: BLE001
        LOGGER.exception("bridge failed: %s", error)
        sys.exit(1)


if __name__ == "__main__":
    main()
